"""Regenerate the committed, offline pinyin table from a pinned MIT data source."""

from hashlib import sha256
from pathlib import Path
from unicodedata import combining, normalize
from urllib.request import urlopen

COMMIT = "fe29ad32bdf352b31a02b9936e537f575432e9a6"
SOURCE_SHA256 = "2342a6f98c85dbc3c8d26aef31744876a36326c6466e51e9a0f16898c36c2011"
BASE = f"https://raw.githubusercontent.com/mozillazg/pinyin-data/{COMMIT}/"
ROOT = Path(__file__).resolve().parent.parent


def syllable(text: str) -> str:
    # Keyboard pinyin uses v for ü. Preserve the distinction from u.
    text = normalize("NFD", text).replace("u\N{COMBINING DIAERESIS}", "v")
    return "".join(character for character in text if not combining(character))


def main() -> None:
    with urlopen(BASE + "pinyin.txt", timeout=30) as response:
        source = response.read()
    if sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("Pinyin source checksum differs from the pinned version")
    entries = []
    for line in source.decode("utf-8").splitlines():
        if not line.startswith("U+"):
            continue
        code, values = line.split(":", 1)
        values = values.split("#", 1)[0].strip().split(",")
        readings = dict.fromkeys(syllable(value) for value in values)
        readings = [value for value in readings if value.isascii() and value.isalpha()]
        if readings:
            entries.append((int(code[2:], 16), ",".join(readings)))
    output = "// Generated by scripts/generate_pinyin.py; pinyin-data (MIT).\n"
    output += "".join(f'{{0x{code:X}, "{values}"}},\n' for code, values in sorted(entries))
    (ROOT / "src/core/pinyin_data.inc").write_text(output, encoding="utf-8")
    with urlopen(BASE + "LICENSE", timeout=30) as response:
        (ROOT / "docs/licenses/pinyin-data-MIT.txt").write_bytes(response.read())
    print(f"Generated {len(entries)} character readings")


if __name__ == "__main__":
    main()
